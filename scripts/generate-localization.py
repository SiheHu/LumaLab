#!/usr/bin/env python3
"""Generate the macOS adapter from a platform-neutral UTF-8 JSON catalog."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
entries = json.loads((root / 'Resources/localization-en.json').read_text())
def swift(value):
    return json.dumps(value, ensure_ascii=False).replace('\\/', '/')
body = '\n'.join(f'        {swift(k)}: {swift(v)},' for k,v in sorted(entries.items()))
(root / 'Sources/LumaLab/LocalizationCatalog.swift').write_text('// Generated by scripts/generate-localization.py; edit Resources/localization-en.json.\nimport Foundation\n\nenum LocalizationCatalog {\n    static let english: [String: String] = [\n' + body + '\n    ]\n}\n')
print(f'Generated {len(entries)} localization entries')
